import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright-core';

export async function verifyEventEntry({site,operator,desk}) {
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:760},reducedMotion:'reduce'});
    await context.addCookies([{name:'payload-token',value:operator,url:site,httpOnly:true,sameSite:'Lax'}]);
    const page=await context.newPage(),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(site+'/admin/operations?tab=registrations&event=ops-integration');
    const registration=page.locator('details.editor-row').filter({hasText:'集成玩家'});
    await registration.locator('summary').click();
    const phone=registration.locator('.op-review-facts > div').filter({has:page.getByText('电话号码',{exact:true})});
    await phone.locator('dd').getByText('13800000009',{exact:true}).waitFor();
    const wechat=registration.locator('.op-review-facts > div').filter({has:page.getByText('微信',{exact:true})});
    await wechat.locator('dd').getByText('ops_player',{exact:true}).waitFor();
    await page.goto(site+'/admin/operations?tab=events&new=1');
    await page.getByRole('heading',{name:'新建玩家计划',exact:true}).waitFor();
    console.log('活动入口浏览器：编辑内外部报名设置…');
    const category=page.getByRole('combobox',{name:'活动类型',exact:true});
    assert.deepEqual(await category.locator('option').allTextContents(),['赛事','沙龙','合作']);
    await category.selectOption('activity');
    const name='报名入口验收 '+randomUUID();
    await page.getByLabel('活动名称',{exact:true}).fill(name);
    await page.getByLabel('活动介绍',{exact:true}).fill(Array.from({length:70},(_,i)=>'第 '+i+' 段：一起探索并完成一个真实项目，记录各自的尝试和反馈。').join('\n\n'));
    await page.getByLabel('对外展示日期',{exact:true}).fill((new Date().getUTCFullYear()+1)+'.12.01');
    const entry=page.getByLabel('报名入口',{exact:true});
    assert.equal(await entry.inputValue(),'website');
    await page.getByLabel('报名确认方式',{exact:true}).selectOption('review');
    await entry.selectOption('external');
    assert.equal(await page.getByRole('heading',{name:'报名问题',exact:true}).count(),0);
    const externalUrl='https://example.test/enroll?event=01';
    await page.getByLabel('外部报名链接',{exact:true}).fill(externalUrl);
    await page.getByRole('button',{name:'发布活动',exact:true}).click();
    await page.getByText('已发布到官网。',{exact:true}).waitFor();
    const id=new URL(page.url()).searchParams.get('edit');assert.ok(id);
    const external=await desk('staff/events/'+id);assert.equal(external.registrationDestination,'external');
    assert.equal(external.category,'activity');assert.equal(external.type,'合作');
    await page.getByRole('button',{name:'预览活动',exact:true}).click();
    await page.getByRole('heading',{name:'外部报名',exact:true}).waitFor();
    await page.getByText(externalUrl,{exact:true}).waitFor();

    console.log('活动入口浏览器：检查活动详情与固定布局…');
    await page.goto(site+'/players?event='+id);
    await page.getByRole('heading',{name,exact:true}).waitFor();
    assert.equal(await page.getByRole('link',{name:'活动报名',exact:true}).count(),0);
    await page.getByRole('link',{name:'参与合作',exact:true}).waitFor();
    const participation=page.locator('.event-entry-facts .event-entry-participation');
    assert.equal(await participation.locator('dt').innerText(),'参与方式');
    assert.equal(await participation.getByRole('link',{name:/^参与(赛事|沙龙|合作)$/}).getAttribute('href'),externalUrl);
    const fonts=await page.locator('.event-entry-facts dt').evaluateAll(els=>els.map(el=>[getComputedStyle(el).fontSize,getComputedStyle(el).fontWeight].join('/')));
    assert.equal(new Set(fonts).size,1);
    const team=page.locator('.detail-section-actions').getByRole('link',{name:'组队招募',exact:true});await team.waitFor();
    const share=page.getByRole('button',{name:'分享',exact:true});
    const style=el=>{const s=getComputedStyle(el);return [s.borderRadius,s.borderWidth,s.fontSize,s.minHeight,s.padding]};
    assert.deepEqual(await team.evaluate(style),await share.evaluate(style));
    async function pinned(selector) {
      const side=page.locator(selector);
      const start=await side.evaluate(el=>el.getBoundingClientRect().top+scrollY);
      await page.evaluate(y=>scrollTo(0,y),start+200);
      const first=await side.evaluate(el=>el.getBoundingClientRect().top);
      await page.evaluate(y=>scrollTo(0,y),start+600);
      const second=await side.evaluate(el=>el.getBoundingClientRect().top);
      assert.ok(Math.abs(first-second)<2,`信息栏未固定：${first} -> ${second}`);
      assert.ok(second>=0);
      assert.equal(await side.evaluate(el=>getComputedStyle(el).position),'sticky');
    }
    await pinned('.event-entry');
    const sidebarRect=await page.locator('.event-entry').boundingBox();
    const beforeWheel=await page.evaluate(()=>scrollY);
    await page.mouse.move(sidebarRect.x+20,sidebarRect.y+20);
    await page.mouse.wheel(0,160);
    await page.waitForFunction(y=>scrollY>y,beforeWheel);
    await page.setViewportSize({width:1440,height:500});
    await page.evaluate(()=>scrollTo(0,950));
    assert.equal(await page.locator('.event-entry').evaluate(el=>getComputedStyle(el).position),'sticky');
    assert.ok(await page.locator('.event-entry').evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight));
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    await page.evaluate(()=>scrollTo(0,0));
    await page.waitForFunction(()=>scrollY===0);
    const mobileStart=await page.locator('.event-entry').evaluate(el=>({top:el.getBoundingClientRect().top,y:scrollY}));
    await page.evaluate(()=>scrollTo(0,300));
    await page.waitForFunction(()=>scrollY===300);
    const mobileEnd=await page.locator('.event-entry').evaluate(el=>({top:el.getBoundingClientRect().top,y:scrollY,position:getComputedStyle(el).position}));
    assert.notEqual(mobileEnd.position,'sticky');
    assert.ok(Math.abs((mobileStart.top-mobileEnd.top)-(mobileEnd.y-mobileStart.y))<2,JSON.stringify({mobileStart,mobileEnd}));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.goto(site+'/players?event='+id+'&view=register');
    await page.getByRole('link',{name:'前往报名',exact:false}).waitFor();
    assert.equal(await page.getByRole('button',{name:'提交报名',exact:true}).count(),0);
    await page.route('https://example.test/**',route=>route.fulfill({contentType:'text/html; charset=utf-8',body:'<h1>外部主办方报名</h1>'}));
    await page.getByRole('link',{name:'前往报名',exact:false}).click();
    await page.getByRole('heading',{name:'外部主办方报名'}).waitFor();

    console.log('活动入口浏览器：切换官网报名并发布招募…');
    // Check both kinds of registration with the actual editor and business API.
    await page.goto(site+'/admin/operations?tab=events&edit='+id);
    await entry.selectOption('website');
    assert.equal(await page.getByLabel('报名确认方式',{exact:true}).inputValue(),'review');
    await page.getByRole('heading',{name:'报名问题',exact:true}).waitFor();
    await page.getByRole('button',{name:'发布活动',exact:true}).click();
    await page.getByText('已发布到官网。',{exact:true}).waitFor();
    await page.goto(site+'/players?event='+id);
    await page.getByRole('link',{name:/^参与(赛事|沙龙|合作)$/}).click();
    await page.getByRole('button',{name:'提交报名',exact:true}).waitFor();
    await page.getByText('主办方审核后确认报名。',{exact:false}).waitFor();

    const signup=await context.request.post(site+'/api/community/register',{headers:{'x-community-request':'1'},data:{email:randomUUID()+'@example.test',password:randomUUID(),name:'报名入口验收玩家'}});
    assert.ok(signup.ok());
    const response=await context.request.post(site+'/api/community/projects',{headers:{'x-community-request':'1'},data:{name:'组队验收项目',summary:'检查组队入口',description:('项目介绍内容，便于验证滚动时项目信息固定。\n\n').repeat(100),demoUrl:'https://example.test/work',imageUrl:'https://example.test/cover.jpg',bannerUrl:'https://example.test/banner.jpg'}});
    assert.ok(response.ok(),await response.text());const project=await response.json();
    await page.goto(site+'/players?event='+id);
    await page.locator('.detail-section-actions').getByRole('link',{name:'组队招募',exact:true}).click();
    await page.getByLabel('关联我的项目',{exact:false}).selectOption(project.id);
    for(const [label,value]of [['招募标题','报名期的组队招募'],['项目简介','做一个实用的项目'],['希望招募的伙伴','设计和开发伙伴'],['参与内容','共同设计和开发'],['具体要求','愿意沟通'],['公开联系方式','team@example.test']])await page.getByLabel(label,{exact:false}).fill(value);
    const publishButton=page.getByRole('button',{name:'发布招募',exact:true});
    await publishButton.scrollIntoViewIfNeeded();
    const publishRect=await publishButton.boundingBox(),returnRect=await page.getByRole('link',{name:'返回',exact:true}).boundingBox();
    assert.ok(returnRect.y<publishRect.y);
    assert.equal(await page.locator('.community-form-action-note').count(),0);
    assert.equal(await page.getByLabel('项目简介',{exact:false}).getAttribute('maxlength'),'30');
    await publishButton.click();
    await page.locator('.community-team-project').filter({hasText:'组队验收项目'}).waitFor();
    const card=page.locator('.community-team-link').first();
    assert.equal(await card.locator('.community-team-project').innerText(),'组队验收项目');
    assert.equal(await card.locator('h3').innerText(),'组队验收项目');
    assert.equal(await card.getByText('报名期的组队招募',{exact:true}).count(),0);
    assert.ok(Array.from(await card.locator('.community-team-summary').innerText()).length<=30);
    await card.click();
    await page.locator('.recruitment-detail h1').waitFor();
    const publisher=page.locator('.recruitment-detail-meta a').first();
    assert.equal(await publisher.innerText(),'报名入口验收玩家');
    assert.equal(await page.locator('.recruitment-detail-meta a').nth(1).innerText(),name);
    const guest=await browser.newPage({viewport:{width:390,height:844}});
    await guest.goto(new URL(await publisher.getAttribute('href'),site).href);
    await guest.getByRole('heading',{name:'报名入口验收玩家',exact:true,level:1}).waitFor();
    assert.equal(await guest.getByRole('link',{name:'修改项目',exact:true}).count(),0);
    await guest.close();
    await publisher.click();
    await page.getByRole('heading',{name:'报名入口验收玩家',exact:true,level:1}).waitFor();
    await page.locator('.public-player-page').getByRole('link',{name:'返回',exact:true}).click();
    await page.locator('.recruitment-detail h1').waitFor();
    assert.equal(await page.locator('.detail-hero').count(),0);
    await page.getByRole('link',{name:'返回',exact:true}).click();
    await desk('staff/events/'+id,'POST',{status:'active',category:'competition',submissionsOpen:true});await desk('staff/events/'+id+'/publish','POST',{});
    await page.goto(site+'/players?event='+id);
    await page.getByRole('link',{name:'参与赛事',exact:true}).waitFor();
    assert.equal(await page.getByRole('link',{name:'查看本场影像',exact:false}).count(),0);
    await page.getByRole('link',{name:'参与赛事',exact:true}).click();
    await page.getByRole('button',{name:'提交报名',exact:true}).waitFor();
    for(let i=0;i<3;i++){
      const result=await context.request.post(site+'/api/community/projects',{headers:{'x-community-request':'1'},data:{eventId:id,name:'卡片验收作品 '+i,summary:'作品介绍',description:'作品详情。',demoUrl:'https://example.test/work/'+i,imageUrl:'https://example.test/cover.jpg',bannerUrl:'https://example.test/banner.jpg'}});
      assert.ok(result.ok());const work=await result.json();
      await desk('staff/projects/'+work.id+'/review','POST',{status:'approved'});
    }
    await page.setViewportSize({width:1440,height:760});
    await page.goto(site+'/players?event='+id);
    await page.locator('#event-works .community-list-card').first().waitFor();
    assert.equal(await page.locator('#event-works .community-grid').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),3);
    const titleSizes=await page.locator('#event-overview > h2,#event-teams > h2,#event-works > h2').evaluateAll(els=>els.map(el=>getComputedStyle(el).fontSize));
    assert.equal(new Set(titleSizes).size,1);
    assert.ok((await page.locator('#event-works .community-list-card').first().boundingBox()).width>170);
    await desk('staff/events/'+id,'POST',{category:'salon'});await desk('staff/events/'+id+'/publish','POST',{});
    await page.reload();await page.getByRole('link',{name:'参与沙龙',exact:true}).waitFor();
    await page.locator('.detail-section-actions').getByRole('link',{name:'组队招募',exact:true}).click();
    await page.getByRole('button',{name:'发布招募',exact:true}).waitFor();
    await page.setViewportSize({width:1440,height:760});
    await page.goto(site+'/plaza?project='+project.id);
    await page.getByRole('heading',{name:'项目信息',exact:true}).waitFor();
    await pinned('.project-detail-side');
    await page.setViewportSize({width:390,height:844});
    assert.notEqual(await page.locator('.project-detail-side').evaluate(el=>getComputedStyle(el).position),'sticky');
    assert.ok(!errors.length,errors.join('\n'));
    await desk('staff/events/'+id,'POST',{category:'activity',type:'合作'});await desk('staff/events/'+id+'/publish','POST',{});
    await page.goto(site+'/admin/operations?tab=events&category=activity');
    const typeFilters=page.getByRole('group',{name:'活动类型'});
    await typeFilters.getByRole('button',{name:'合作',exact:true}).waitFor();
    assert.deepEqual(await typeFilters.getByRole('button').allTextContents(),['全部','赛事','沙龙','合作']);
    await page.waitForFunction(()=>document.querySelector('.op-category-tabs [aria-pressed="true"]')?.textContent==='合作');
    await page.getByText(name,{exact:true}).waitFor();
    console.log('活动入口浏览器通过：后台内外部切换、外链跳转、官网报名表、两种状态组队发布、同款按钮、桌面活动及项目固定、短屏与手机滚动。');
  } finally {await browser.close();}
}
